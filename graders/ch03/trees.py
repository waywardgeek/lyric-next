def main():
    command = sys.argv[1:]
    if command[:1] == ['--']:
        command.pop(0)
    if not command:
        raise SystemExit('usage: trees.py -- COMMAND ...')
    failures = []
    count = 0
    with tempfile.TemporaryDirectory() as directory:
        path = Path(directory) / 'case.ly'
        for label, expr, source, expected in cases():
            count += 1
            path.write_text(source, encoding='utf8')
            mode = '--inspect-expression' if expr else '--inspect-syntax'
            try:
                result = subprocess.run(command + [mode, str(path)], capture_output=True, text=True, timeout=10)
                actual = json.loads(result.stdout)
                if result.returncode != 0 or result.stderr or not same_json(actual, expected):
                    raise ValueError(f'exit={result.returncode}, stderr={result.stderr!r}, tree={actual!r}')
            except (ValueError, subprocess.TimeoutExpired) as error:
                failures.append(label)
                print(f'FAIL {label}: {error}')
    print(f'{count - len(failures)}/{count} syntax trees passed')
    return bool(failures)


if __name__ == '__main__':
    raise SystemExit(main())
