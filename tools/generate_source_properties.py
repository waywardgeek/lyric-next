"""Generate source-wide Unicode bans from the pinned upstream data.

This is an authoring utility, not a grader. The compiler does not invoke it at
runtime. Keep the official data and this utility out of a student's solution.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / 'unicode' / '16.0.0'


def property_ranges(filename, wanted):
    result = []
    for line in (DATA / filename).read_text().splitlines():
        fields = line.split('#', 1)[0].strip().split(';')
        if len(fields) < 2 or fields[1].strip() != wanted:
            continue
        ends = fields[0].strip().split('..')
        result.append((int(ends[0], 16), int(ends[-1], 16)))
    return result


ranges = property_ranges('DerivedCoreProperties.txt', 'Default_Ignorable_Code_Point')
bidi_ranges = property_ranges('PropList.txt', 'Bidi_Control')
for lo, hi in bidi_ranges:
    for scalar in range(lo, hi + 1):
        assert any(a <= scalar <= b for a, b in ranges), 'Bidi property no longer a subset'
ranges += bidi_ranges
for line in (DATA / 'UnicodeData.txt').read_text().splitlines():
    fields = line.split(';')
    if fields[2] == 'Cc':
        scalar = int(fields[0], 16)
        if scalar not in (9, 10, 13):
            ranges.append((scalar, scalar))

# Collapse overlap and adjacency: classification needs only membership, not the
# original property label. Diagnostics report the offending code point.
merged = []
for lo, hi in sorted(ranges):
    if merged and lo <= merged[-1][1] + 1:
        merged[-1] = (merged[-1][0], max(merged[-1][1], hi))
    else:
        merged.append((lo, hi))

text = '''// Generated by tools/generate_source_properties.py from Unicode 16.0.0.
// Unicode data license: ../../unicode/LICENSE.txt (relative to this file). Do not edit ranges by hand.
namespace Lyric;

// Shared immutable value data; not a registry of runtime objects.
internal static partial class SourceRules
{
    internal const string UnicodeVersion = "16.0.0";

    // Sorted inclusive pairs. HT/LF/CR are handled by the scanner, not this table.
    private static readonly int[] ForbiddenRanges =
    [
'''
text += ''.join(f'        0x{lo:X}, 0x{hi:X},\n' for lo, hi in merged)
text += '    ];\n}\n'
(ROOT / 'compiler/Common/SourceRules.Data.cs').write_text(text)
print(f'Generated {len(merged)} forbidden ranges.')
